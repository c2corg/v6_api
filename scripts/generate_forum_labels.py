"""Generate c2corg_api/views/forum_labels.py from the c2c_ui translations."""

# The forum topic titles name the document type in the words of the site:
#   uv run python scripts/generate_forum_labels.py ../c2c_ui
# A label missing in a language falls back to English, then to the key itself.

import json
import sys
from pathlib import Path

from c2corg_api.models.common.attributes import default_langs, waypoint_types

DOCUMENT_TYPES = [
    'area',
    'article',
    'book',
    'image',
    'map',
    'outing',
    'route',
    'waypoint',
    'xreport',
]
OUTPUT = Path(__file__).parent.parent / 'c2corg_api' / 'views' / 'forum_labels.py'


def load_catalogs(c2c_ui):
    """Load the translation catalog of each language of the API."""
    translations = Path(c2c_ui) / 'src' / 'translations'
    catalogs = {}
    for lang in default_langs:
        name = 'zh_CN' if lang == 'zh' else lang
        with open(translations / f'{name}.json', encoding='utf-8') as f:
            catalogs[lang] = json.load(f)[name]
    return catalogs


def translate(catalog, key, context):
    """Give the translation of a key in a catalog, or None."""
    value = catalog.get(key)
    if isinstance(value, dict):
        value = value.get(context or '$$noContext')
    return value


def label(catalogs, lang, key, context=None):
    """Give the label of a key in a language, starting with a capital."""
    value = (
        translate(catalogs[lang], key, context)
        or translate(catalogs['en'], key, context)
        or key
    ).strip()
    return value[:1].upper() + value[1:]


def write_labels(catalogs):
    """Write the module of the labels."""
    lines = [
        '"""Labels of the forum topic titles, in each language."""',
        '',
        '# Generated by scripts/generate_forum_labels.py from the c2c_ui translation',
        '# catalogs, so the forum uses the words of the site. A missing translation',
        '# falls back to English.',
        '',
        'DOCUMENT_TYPE_LABELS = {',
    ]
    for lang in default_langs:
        lines.append(f'    {lang!r}: {{')
        lines += [
            f'        {t!r}: {label(catalogs, lang, t)!r},' for t in DOCUMENT_TYPES
        ]
        lines.append('    },')
    lines += ['}', '', 'WAYPOINT_TYPE_LABELS = {']
    for lang in default_langs:
        lines.append(f'    {lang!r}: {{')
        lines += [
            f'        {w!r}: {label(catalogs, lang, w, "waypoint_types")!r},'
            for w in waypoint_types
        ]
        lines.append('    },')
    lines.append('}')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit('usage: generate_forum_labels.py <path of the c2c_ui repository>')
    write_labels(load_catalogs(sys.argv[1]))
